def age_group(age: int | None) -> str:
    if age is None:
        return "unknown"
    return next((g for lo, hi, g in AGE_GROUPS if lo <= age <= hi), "unknown")


def birthday_text(gender: str | None, age: int | None, mention: str) -> str:
    by_gender = BIRTHDAY.get(gender) or BIRTHDAY[None]
    variants = by_gender.get(age_group(age)) or by_gender.get("unknown") or BIRTHDAY[None]["unknown"]
    return random.choice(variants).format(name=mention, age=age or "")


